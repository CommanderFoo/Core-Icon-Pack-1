--[[
	Hi.

	Just a simple flat icon pack.  A few I had to modify that didn't have a background as
	transparency isn't supported for screen shots.

	Each icon is 128 x 128 px but scaled down to 64 x 64.

	I made a template for each icon so it's easy to just drag and drop into the hierarchy.

	Icons come from: iconarchive.com

	There is an example template you can drop in to see all of them.

	If you would prefer to host the pack for yourself, you can download the texture atlas:

	https://pixeldepth.net/core/icon-packs/social-media-icon-pack-1.png

	- Create a blank project
	- Publish game as unlisted
	- Use the image you downloaded as the screenshot

	To use in a project:

	- Create UI Image
	- Set "Game ID" to the slug of your unlisted game (i.e "9492fc/icon-pack-1")
	- Select screenshot index 
	- Set the size of the image and x / y offset
]]